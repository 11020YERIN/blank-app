
import streamlit as st

# -----------------------------------------------------------------------------
# 1. 데이터 베이스 구축 (리스트 활용)
# -----------------------------------------------------------------------------
음료_이름_리스트 = ['콜라', '사이다', '오렌지주스', '이온음료', '에너지드링크']
# 각 음료별 100mL당 당류 함량(g)
당류_함량_리스트 = [10.8, 8.4, 10.0, 6.0, 15.0]

# -----------------------------------------------------------------------------
# Streamlit UI 레이아웃 선언
# -----------------------------------------------------------------------------
st.title("🥤 음료 설탕 중독 진단기")
st.write("오늘 마신 음료를 기록하고, 하루 당류 섭취량과 중독 위험도를 진단해보세요!")
st.markdown("---")

# 1. 입력 단계 (Input)
st.subheader("1. 음료 입력하기")

# 유저가 마신 음료 종류와 용량을 선택할 수 있는 폼 구성
selected_drink = st.selectbox("마신 음료를 선택하세요:", 음료_이름_리스트)
amount = st.number_input("마신 양(mL)을 입력하세요:", min_value=0, value=250, step=50)

